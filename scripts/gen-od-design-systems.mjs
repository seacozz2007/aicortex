/**
 * Sync Design Studio design-system catalog from Open Design bundled packages.
 * Copies DESIGN.md to public/ for lazy loading at session create time.
 */
import fs from "fs";
import path from "path";

const OD_DS_ROOT = "D:/CODE/open-design/design-systems";
const OD_PLUGIN_DS = "D:/CODE/open-design/plugins/_official/design-systems";
const OUT_TS = "packages/core/design/od-design-system-data.ts";
const PUBLIC_DS = "apps/web/public/design-systems";

function extractSwatches(dsDir) {
  const tokensPath = path.join(dsDir, "design-tokens.json");
  if (fs.existsSync(tokensPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(tokensPath, "utf8"));
      const colors = [];
      const seen = new Set();
      const priority = ["A1-identity", "B-slot", "A1-structure", "A2"];
      const tokens = [...(data.tokens ?? [])].sort((a, b) => {
        const ai = priority.indexOf(a.layer ?? "");
        const bi = priority.indexOf(b.layer ?? "");
        return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi);
      });
      for (const token of tokens) {
        if (token.type !== "color") continue;
        const hex = String(token.value ?? "").trim().toLowerCase();
        if (!/^#[0-9a-f]{3,8}$/i.test(hex) || seen.has(hex)) continue;
        seen.add(hex);
        colors.push(hex);
        if (colors.length >= 4) return colors;
      }
      if (colors.length > 0) return colors;
    } catch {
      /* fall through */
    }
  }

  const designPath = path.join(dsDir, "DESIGN.md");
  if (!fs.existsSync(designPath)) return undefined;
  const body = fs.readFileSync(designPath, "utf8");
  const hexes = [];
  const seen = new Set();
  for (const match of body.matchAll(/`(#(?:[0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8}))`/gi)) {
    const hex = match[1].toLowerCase();
    if (seen.has(hex)) continue;
    seen.add(hex);
    hexes.push(hex);
    if (hexes.length >= 4) return hexes;
  }
  return hexes.length > 0 ? hexes : undefined;
}

function summaryFromDesignMd(dsDir) {
  const designPath = path.join(dsDir, "DESIGN.md");
  if (!fs.existsSync(designPath)) return "";
  const body = fs.readFileSync(designPath, "utf8");
  const lines = body.split(/\r?\n/);
  const quoteParts = [];
  for (const line of lines) {
    if (!line.startsWith(">")) {
      if (quoteParts.length > 0) break;
      continue;
    }
    const text = line.replace(/^>\s?/, "").trim();
    if (!text || text.startsWith("Category:")) continue;
    quoteParts.push(text);
  }
  if (quoteParts.length > 0) return quoteParts.join(" ").slice(0, 160);
  const prose = lines.map((line) => line.trim()).filter(Boolean);
  for (const line of prose) {
    if (line.startsWith("#")) continue;
    if (line.startsWith(">")) continue;
    if (line.startsWith("---")) continue;
    return line.slice(0, 160);
  }
  return "";
}

function readPluginI18n(id) {
  const pluginPath = path.join(OD_PLUGIN_DS, id, "open-design.json");
  if (!fs.existsSync(pluginPath)) return {};
  try {
    const plugin = JSON.parse(fs.readFileSync(pluginPath, "utf8"));
    return {
      labelZh: plugin.title_i18n?.["zh-CN"] ?? plugin.title_i18n?.["zh-Hans"],
      summaryZh: plugin.description_i18n?.["zh-CN"] ?? plugin.description_i18n?.["zh-Hans"],
    };
  } catch {
    return {};
  }
}

function main() {
  const entries = fs
    .readdirSync(OD_DS_ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
    .map((d) => {
      const id = d.name;
      const dsDir = path.join(OD_DS_ROOT, id);
      const manifestPath = path.join(dsDir, "manifest.json");
      if (!fs.existsSync(manifestPath)) return null;

      const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
      const designSrc = path.join(dsDir, "DESIGN.md");
      if (!fs.existsSync(designSrc)) return null;

      const i18n = readPluginI18n(id);
      const summary =
        (manifest.description ?? "")
          .replace(/^Bundled Open Design package for .+, derived from curated DESIGN\.md.*$/i, "")
          .trim() || summaryFromDesignMd(dsDir);

      const destDir = path.join(PUBLIC_DS, id);
      fs.mkdirSync(destDir, { recursive: true });
      fs.copyFileSync(designSrc, path.join(destDir, "DESIGN.md"));

      return {
        id,
        label: manifest.name ?? id,
        labelZh: i18n.labelZh,
        category: manifest.category ?? "General",
        summary: summary.slice(0, 200),
        summaryZh: i18n.summaryZh?.slice(0, 200),
        swatches: extractSwatches(dsDir),
        isDefault: id === "default",
      };
    })
    .filter(Boolean)
    .sort((a, b) => {
      if (a.isDefault !== b.isDefault) return a.isDefault ? -1 : 1;
      return a.label.localeCompare(b.label);
    });

  const ts = `/** Generated by scripts/gen-od-design-systems.mjs — do not edit manually. */
export interface DesignSystemCatalogEntry {
  id: string;
  label: string;
  labelZh?: string;
  category: string;
  summary: string;
  summaryZh?: string;
  swatches?: string[];
  isDefault?: boolean;
}

export const DESIGN_SYSTEM_CATALOG: DesignSystemCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUT_TS), { recursive: true });
  fs.writeFileSync(OUT_TS, ts, "utf8");
  console.log(`Wrote ${entries.length} design systems -> ${OUT_TS}`);
  console.log(`Copied DESIGN.md files -> ${PUBLIC_DS}`);
}

main();
